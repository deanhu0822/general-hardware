"use client";

import { useCallback, useMemo, useState, type ReactNode } from "react";
import { AlertTriangle, ChevronDown, Download, FileText, ShieldAlert } from "lucide-react";
import { Badge } from "@/components/ui/badge";
import { Button } from "@/components/ui/button";
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from "@/components/ui/card";
import { Collapsible, CollapsibleContent, CollapsibleTrigger } from "@/components/ui/collapsible";
import { Sheet, SheetContent, SheetDescription, SheetHeader, SheetTitle } from "@/components/ui/sheet";
import { Table, TableBody, TableCell, TableHead, TableHeader, TableRow } from "@/components/ui/table";
import { sectorLabel } from "@/lib/packets/client-model";
import type { Anchor, Citation, Packet } from "@/lib/packets/model";

export type SourceText = { sourceId: string; content: string };
export type PacketViewProps = {
  packet: Packet;
  mode: "sample" | "delivered" | "study";
  /** Presentation variant for the usability study. "A" is the frozen baseline. */
  presentation?: "A" | "B";
  /** Inline source text (sample/study) or a loader (delivered, authenticated). */
  sources?: SourceText[];
  loadSource?: (sourceId: string) => Promise<SourceText>;
  downloadHref?: string;
  actions?: ReactNode;
  onSourceOpen?: (sourceId: string) => void;
  onSelectEvidence?: (id: string) => void;
  selectedEvidence?: string | null;
};

const cite = (c: Citation) => `${c.sourceId} · ${c.anchorId}`;

export function PacketView(p: PacketViewProps) {
  const { packet, mode } = p;
  const presentation = p.presentation ?? "A";
  const [sheet, setSheet] = useState<{ sourceId: string; anchorId?: string } | null>(null);
  const [loaded, setLoaded] = useState<Record<string, SourceText>>(() => Object.fromEntries((p.sources ?? []).map((s) => [s.sourceId, s])));
  const [loadError, setLoadError] = useState<string | null>(null);
  const anchorsBySource = useMemo(() => {
    const m = new Map<string, Anchor[]>();
    for (const s of packet.sourceRegister) m.set(s.sourceId, s.anchors);
    return m;
  }, [packet]);
  const open = useCallback(
    async (sourceId: string, anchorId?: string) => {
      setSheet({ sourceId, anchorId });
      setLoadError(null);
      p.onSourceOpen?.(sourceId);
      if (!loaded[sourceId] && p.loadSource) {
        try {
          const s = await p.loadSource(sourceId);
          setLoaded((prev) => ({ ...prev, [sourceId]: s }));
        } catch (error) {
          setLoadError(error instanceof Error ? error.message : "The source could not be loaded.");
        }
      }
    },
    [loaded, p],
  );
  const gapById = new Map(packet.evidenceGaps.map((g) => [g.id, g]));
  const nextGap = gapById.get(packet.nextAction.gapId);
  const origin = packet.receipt.origin;

  return (
    <article className="space-y-6" aria-labelledby="packet-title">
      <header className="space-y-3">
        <div className="flex flex-wrap items-center gap-2">
          <Badge variant="outline" className="border-primary/40 bg-primary/5 text-primary">
            Packet ready · advisory preparation
          </Badge>
          <Badge variant="outline" className="gap-1">
            <ShieldAlert className="size-3" aria-hidden="true" /> Not engineering approval
          </Badge>
          {origin === "synthetic-fixture" ? <Badge variant="secondary">Synthetic sample · invented sources</Badge> : null}
          {origin === "test-double" ? <Badge variant="destructive">Test double · no model ran</Badge> : null}
          {origin === "opus-run" ? <Badge variant="secondary">Generated by {packet.receipt.effective?.model ?? packet.receipt.requested?.model ?? "runtime model"}</Badge> : null}
        </div>
        <h1 id="packet-title">J12 connector-change review packet</h1>
        <p className="text-sm text-muted-foreground">
          Request v{packet.summary.requestVersion} · Baseline {packet.summary.baseline} · {packet.summary.sectorTags.map(sectorLabel).join(", ")} · {packet.summary.productLabel}
        </p>
      </header>

      <Card className="liquid-glass">
        <CardHeader>
          <CardDescription className="text-xs font-semibold uppercase tracking-wide text-primary">{presentation === "B" ? "Next required action before any approval" : "Next action"}</CardDescription>
          <CardTitle className="text-lg leading-snug">{packet.nextAction.action}</CardTitle>
        </CardHeader>
        <CardContent className="space-y-2 text-sm">
          <dl className="grid gap-1 sm:grid-cols-[9rem_1fr]">
            <dt className="text-muted-foreground">Owner</dt>
            <dd>{packet.nextAction.ownerRole}</dd>
            <dt className="text-muted-foreground">Required input</dt>
            <dd>{packet.nextAction.requiredInput}</dd>
            <dt className="text-muted-foreground">Evidence gap</dt>
            <dd>
              <a href={`#gap-${packet.nextAction.gapId}`} className="text-primary underline-offset-4 hover:underline">
                {nextGap?.gap ?? packet.nextAction.gapId}
              </a>
            </dd>
            <dt className="text-muted-foreground">Sources</dt>
            <dd>
              <Citations onOpen={open} items={packet.nextAction.citations} label="next action" />
            </dd>
          </dl>
          {(p.downloadHref || p.actions) && (
            <div className="flex flex-wrap items-center gap-2 pt-2">
              {p.downloadHref ? (
                <Button asChild>
                  <a href={p.downloadHref} download>
                    <Download data-icon="inline-start" /> Download Markdown
                  </a>
                </Button>
              ) : null}
              {p.actions}
            </div>
          )}
        </CardContent>
      </Card>

      <section aria-labelledby="summary-h" className="space-y-2">
        <h2 id="summary-h">Summary</h2>
        <p className="font-medium">{packet.summary.headline}</p>
        <p className="text-sm text-muted-foreground">{packet.summary.objective}</p>
      </section>

      <section aria-labelledby="alts-h" className="space-y-3">
        <h2 id="alts-h">Alternatives</h2>
        <div className="grid gap-3 md:grid-cols-2">
          {packet.alternatives.map((a) => (
            <Card key={a.id}>
              <CardHeader>
                <CardDescription className="text-xs uppercase tracking-wide">{a.kind === "retain-investigate" ? "Retain / investigate" : a.kind === "replacement" ? "Replacement" : "Customer candidate"}</CardDescription>
                <CardTitle className="text-base">{a.title}</CardTitle>
              </CardHeader>
              <CardContent className="space-y-2 text-sm">
                <p>{a.description}</p>
                {a.prerequisites.length ? (
                  <div>
                    <p className="text-xs font-medium text-muted-foreground">Prerequisites</p>
                    <ul className="list-disc space-y-0.5 pl-5">
                      {a.prerequisites.map((x, i) => (
                        <li key={i}>{x}</li>
                      ))}
                    </ul>
                  </div>
                ) : null}
                <Citations onOpen={open} items={a.citations} label="alternative" />
              </CardContent>
            </Card>
          ))}
        </div>
      </section>

      <section aria-labelledby="gaps-h" className="space-y-3">
        <div className="flex items-center gap-2">
          <AlertTriangle className="size-4 text-amber-600" aria-hidden="true" />
          <h2 id="gaps-h">{presentation === "B" ? "Missing evidence (blocks approval)" : "Evidence gaps"}</h2>
        </div>
        <ul className="space-y-2">
          {packet.evidenceGaps.map((g) => {
            const selected = p.selectedEvidence === g.id;
            return (
              <li key={g.id} id={`gap-${g.id}`} className={g.id === packet.nextAction.gapId || selected ? "liquid-glass rounded-lg p-3" : "rounded-lg border border-border bg-background p-3"}>
                <div className="flex flex-wrap items-start justify-between gap-2">
                  <p className="font-medium">
                    {g.gap} {g.id === packet.nextAction.gapId ? <Badge variant="secondary" className="ml-1">drives next action</Badge> : null}
                  </p>
                  {mode === "study" && p.onSelectEvidence ? (
                    <Button type="button" size="sm" variant={selected ? "default" : "outline"} aria-pressed={selected} onClick={() => p.onSelectEvidence?.(g.id)}>
                      {selected ? "Selected" : "Select this gap"}
                    </Button>
                  ) : null}
                </div>
                <p className="mt-1 text-sm text-muted-foreground">{g.whyItMatters}</p>
                <div className="mt-1 text-xs">
                  <Citations onOpen={open} items={g.citations} label="evidence gap" />
                </div>
              </li>
            );
          })}
        </ul>
      </section>

      <Section title={`Affected artifacts (${packet.affectedArtifacts.length})`} defaultOpen>
        <Table>
          <TableHeader>
            <TableRow>
              <TableHead>Artifact</TableHead>
              <TableHead>Status</TableHead>
              <TableHead>Basis</TableHead>
              <TableHead>Sources</TableHead>
            </TableRow>
          </TableHeader>
          <TableBody>
            {packet.affectedArtifacts.map((a) => (
              <TableRow key={a.id}>
                <TableCell className="font-medium">{a.label}</TableCell>
                <TableCell>
                  <Badge variant={a.status === "confirmed" ? "default" : "outline"}>{a.status}</Badge>
                </TableCell>
                <TableCell className="whitespace-normal text-sm text-muted-foreground">{a.basis}</TableCell>
                <TableCell>
                  <Citations onOpen={open} items={a.citations} label="artifact" />
                </TableCell>
              </TableRow>
            ))}
          </TableBody>
        </Table>
      </Section>

      <Section title={`Known facts: claim → source (${packet.knownFacts.length})`}>
        <Table>
          <TableHeader>
            <TableRow>
              <TableHead>#</TableHead>
              <TableHead>Statement</TableHead>
              <TableHead>Kind</TableHead>
              <TableHead>Sources</TableHead>
            </TableRow>
          </TableHeader>
          <TableBody>
            {packet.knownFacts.map((f) => (
              <TableRow key={f.id}>
                <TableCell className="font-mono text-xs">{f.id}</TableCell>
                <TableCell className="whitespace-normal">{f.statement}</TableCell>
                <TableCell>
                  <Badge variant="outline">{f.kind}</Badge>
                </TableCell>
                <TableCell>
                  <Citations onOpen={open} items={f.citations} label="fact" />
                </TableCell>
              </TableRow>
            ))}
          </TableBody>
        </Table>
      </Section>

      <Section title={`Reviewer questions (${packet.reviewQuestions.length})`}>
        <ul className="space-y-2 text-sm">
          {packet.reviewQuestions.map((q) => (
            <li key={q.id} className="rounded-md border border-border bg-background p-3">
              <p className="font-medium">{q.question}</p>
              <p className="text-muted-foreground">
                Owner: {q.owner}
                {q.prerequisite ? ` · Prerequisite: ${q.prerequisite}` : ""}
              </p>
            </li>
          ))}
        </ul>
      </Section>

      <section aria-labelledby="sources-h" className="space-y-3">
        <div className="flex items-center gap-2">
          <FileText className="size-4" aria-hidden="true" />
          <h2 id="sources-h">Source register</h2>
        </div>
        <div className="overflow-x-auto rounded-lg border border-border bg-background">
          <Table>
            <TableHeader>
              <TableRow>
                <TableHead>Source</TableHead>
                <TableHead>Name</TableHead>
                <TableHead>Revision</TableHead>
                <TableHead>SHA-256</TableHead>
                <TableHead>Excerpts</TableHead>
                <TableHead />
              </TableRow>
            </TableHeader>
            <TableBody>
              {packet.sourceRegister.map((s) => (
                <TableRow key={s.sourceId}>
                  <TableCell className="font-mono text-xs">{s.sourceId}</TableCell>
                  <TableCell className="whitespace-normal">{s.name}</TableCell>
                  <TableCell>{s.revision}</TableCell>
                  <TableCell className="font-mono text-[11px]" title={s.sha256}>
                    {s.sha256.slice(0, 12)}…
                  </TableCell>
                  <TableCell>{s.anchors.length}</TableCell>
                  <TableCell>
                    <Button size="sm" variant="outline" onClick={() => open(s.sourceId)}>
                      Open
                    </Button>
                  </TableCell>
                </TableRow>
              ))}
            </TableBody>
          </Table>
        </div>
      </section>

      <section aria-labelledby="limits-h" className="space-y-2">
        <h2 id="limits-h">Limitations</h2>
        <ul className="list-disc space-y-1 pl-5 text-sm">
          {packet.limitations.map((l, i) => (
            <li key={i}>{l}</li>
          ))}
        </ul>
      </section>

      <Section title="Run receipt">
        <Receipt packet={packet} />
      </Section>

      <Sheet open={!!sheet} onOpenChange={(o) => !o && setSheet(null)}>
        <SheetContent side="right" className="w-full overflow-y-auto sm:max-w-xl data-[side=right]:sm:max-w-xl">
          {sheet ? (
            <SourcePanel
              entry={packet.sourceRegister.find((s) => s.sourceId === sheet.sourceId)}
              anchors={anchorsBySource.get(sheet.sourceId) ?? []}
              highlight={sheet.anchorId}
              source={loaded[sheet.sourceId]}
              error={loadError}
              mode={mode}
            />
          ) : null}
        </SheetContent>
      </Sheet>
    </article>
  );
}

function Citations({ items, label, onOpen }: { items: Citation[]; label: string; onOpen: (sourceId: string, anchorId?: string) => void }) {
  return items.length ? (
    <span className="inline-flex flex-wrap gap-1 align-middle" aria-label={`${label}: ${items.length} source citation${items.length === 1 ? "" : "s"}`}>
      {items.map((c) => (
        <button
          key={`${c.sourceId}:${c.anchorId}`}
          type="button"
          onClick={() => onOpen(c.sourceId, c.anchorId)}
          className="inline-flex min-h-6 items-center rounded border border-border bg-background px-1.5 py-0.5 font-mono text-[11px] text-muted-foreground hover:border-primary hover:text-primary focus-visible:outline-2 focus-visible:outline-ring"
          title={`Open the exact excerpt ${cite(c)}`}
        >
          {cite(c)}
        </button>
      ))}
    </span>
  ) : (
    <span className="text-xs text-muted-foreground">no citation (labeled {label})</span>
  );
}

function Section({ title, children, defaultOpen = false }: { title: string; children: ReactNode; defaultOpen?: boolean }) {
  const [open, setOpen] = useState(defaultOpen);
  return (
    <Collapsible open={open} onOpenChange={setOpen} className="rounded-lg border border-border bg-background">
      <CollapsibleTrigger asChild>
        <button type="button" className="flex w-full items-center justify-between px-4 py-3 text-left" aria-expanded={open}>
          <h2 className="text-base">{title}</h2>
          <ChevronDown className={`size-4 transition-transform ${open ? "rotate-180" : ""}`} aria-hidden="true" />
        </button>
      </CollapsibleTrigger>
      <CollapsibleContent className="px-4 pb-4">{children}</CollapsibleContent>
    </Collapsible>
  );
}

function SourcePanel({ entry, anchors, highlight, source, error, mode }: { entry?: Packet["sourceRegister"][number]; anchors: Anchor[]; highlight?: string; source?: SourceText; error: string | null; mode: PacketViewProps["mode"] }) {
  if (!entry) return <p>Source not found.</p>;
  const sorted = [...anchors].sort((a, b) => a.start - b.start);
  const parts: ReactNode[] = [];
  if (source) {
    let pos = 0;
    for (const a of sorted) {
      if (a.start < pos) continue;
      parts.push(<span key={`t${pos}`}>{source.content.slice(pos, a.start)}</span>);
      parts.push(
        <mark key={a.anchorId} id={`anchor-${a.anchorId}`} className={a.anchorId === highlight ? "ring-2 ring-primary" : ""} title={a.anchorId}>
          {source.content.slice(a.start, a.end)}
        </mark>,
      );
      pos = a.end;
    }
    parts.push(<span key="tail">{source.content.slice(pos)}</span>);
  }
  return (
    <>
      <SheetHeader>
        <SheetTitle className="text-base">
          {entry.sourceId} — {entry.name}
        </SheetTitle>
        <SheetDescription>
          Revision {entry.revision} · {entry.bytes} bytes · imported {entry.importedAt.slice(0, 10)} · SHA-256 <span className="font-mono text-[11px]">{entry.sha256}</span>
          {mode === "sample" || mode === "study" ? " · synthetic fixture" : ""}
        </SheetDescription>
      </SheetHeader>
      <div className="space-y-3 px-4 pb-4 text-sm">
        {highlight ? (
          <div className="rounded-md border border-primary/40 bg-primary/5 p-3">
            <p className="text-xs font-medium text-primary">Cited excerpt {highlight}</p>
            <blockquote className="mt-1 whitespace-pre-wrap">{anchors.find((a) => a.anchorId === highlight)?.excerpt}</blockquote>
          </div>
        ) : null}
        <p className="text-xs text-muted-foreground">
          {anchors.length} cited excerpt{anchors.length === 1 ? "" : "s"} highlighted in the frozen text below. Offsets are character positions in the hashed source.
        </p>
        {error ? <p className="text-destructive">{error}</p> : null}
        {source ? <pre className="excerpt whitespace-pre-wrap rounded-md border border-border bg-muted/40 p-3 font-sans text-[13px] leading-relaxed">{parts}</pre> : !error ? <p className="text-muted-foreground">Loading the frozen source…</p> : null}
      </div>
    </>
  );
}

function Receipt({ packet }: { packet: Packet }) {
  const r = packet.receipt;
  const eff = r.effective;
  return (
    <dl className="grid gap-x-4 gap-y-1 text-sm sm:grid-cols-[11rem_1fr]">
      <dt className="text-muted-foreground">Origin</dt>
      <dd>{r.origin === "opus-run" ? "Live run through the Claude Agent SDK" : r.origin === "synthetic-fixture" ? "Synthetic fixture (no model ran)" : "Test double (no model ran)"}</dd>
      <dt className="text-muted-foreground">Order / run</dt>
      <dd className="font-mono text-xs">
        {r.orderId} · {r.runId} · attempt {r.attempt} · packet v{r.packetVersion} · request v{r.requestVersion}
      </dd>
      <dt className="text-muted-foreground">Manifest digest</dt>
      <dd className="font-mono text-xs break-all">{r.manifestDigest}</dd>
      {r.requested ? (
        <>
          <dt className="text-muted-foreground">Requested</dt>
          <dd>
            {r.requested.model} · start effort {r.requested.effort} · policy {r.requested.policyVersion} · budget ${r.requested.maxBudgetUsd.toFixed(2)} · ≤{r.requested.maxToolCalls} tool calls · ≤{Math.round(r.requested.deadlineMs / 60000)} min
          </dd>
        </>
      ) : null}
      {eff ? (
        <>
          <dt className="text-muted-foreground">Effective</dt>
          <dd>
            {eff.model ?? "unknown"} · effort {eff.effort ?? "unreported"} · context window {eff.contextWindow?.toLocaleString("en-US") ?? "unknown"} · SDK {eff.sdkVersion ?? "—"} · credentials {eff.apiKeySource ?? "—"}
            {eff.mismatch ? <span className="ml-1 text-destructive">MISMATCH: {eff.mismatch}</span> : null}
          </dd>
          <dt className="text-muted-foreground">Effort policy</dt>
          <dd>
            {eff.policyVersion ?? "—"}
            {eff.provisional ? " · provisional default" : ""} · {eff.selectionReason ?? ""} · escalations {eff.escalations}
          </dd>
          {eff.phases?.length ? (
            <>
              <dt className="text-muted-foreground">Phases</dt>
              <dd>
                {eff.phases.map((ph) => `${ph.phase}@${ph.effort}: ${ph.costUsd === null ? "$?" : `$${ph.costUsd.toFixed(4)}`}, ${ph.inputTokens}/${ph.outputTokens} tok, ${(ph.latencyMs / 1000).toFixed(1)}s`).join(" → ")}
              </dd>
            </>
          ) : null}
        </>
      ) : null}
      <dt className="text-muted-foreground">Timing</dt>
      <dd>
        {r.startedAt} → {r.completedAt} · {(r.latencyMs / 1000).toFixed(1)} s
      </dd>
      <dt className="text-muted-foreground">Usage</dt>
      <dd>
        {r.costUsd === null ? "cost not applicable" : `$${r.costUsd.toFixed(4)} (SDK estimate)`} · tokens in/out {r.inputTokens ?? "—"}/{r.outputTokens ?? "—"} · tool calls {r.toolCalls} · repairs {r.repairs}
      </dd>
      <dt className="text-muted-foreground">Validation</dt>
      <dd>
        {r.validation.ok ? "passed" : "FAILED"} at {r.validation.checkedAt} · {r.validation.checks.join(" ")}
      </dd>
    </dl>
  );
}
